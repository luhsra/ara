import graph_tool.util
from ara.graph.mix import ARA_ENTRY_POINT
from ara.steps.instance_graph_stats import MissingInteractions
from ara.steps.util import current_step
import pyllco
from .step import Step
from pydoc import locate
from ara.os.zephyr import Queue, QueueType, ZephyrInstance, Thread, ZephyrKernel, Zephyr, ZephyrOptions, Timer, ISR, ZephyrIRQ
from ara.os.os_base import ControlInstance
from .option import Bool, Option, String, Integer
from ara.util import KConfigFile, get_logger
from ara.os.interrupts import fake_interrupt_function

logger = get_logger("ZephyrStaticPost")

class ZephyrStaticPost(Step):
    """Deserializes the dictionary encoded instance objects generated by the ZephyrStatic step."""

    kconfigfile = Option(name="kconfigfile",
                         help="Path to the app's KConfig file.",
                         ty=String())

    cpu_id = Option(name="cpu_id",
                         help="Path to the app's KConfig file.",
                         ty=Integer(),
                         default_value=0)
    
    enable_missing_interaction_count = Option(
        name="enable_missing_interaction_count",
        help="Use this option in conjunction with InstanceGraphStats step to gather data about missing interactions",
        ty=Bool(),
        default_value=True
    )

    def get_single_dependencies(self):
        return ["ZephyrStatic", "LLVMMap", "SVFAnalyses"]

    @staticmethod
    def create_static_instance(instances, label: str, obj: ZephyrInstance, ident: str, sched_on: bool):
        v = instances.add_vertex()
        instances.vp.label[v] = label
        instances.vp.obj[v] = obj
        instances.vp.id[v] = ident
        # Static instances are always unique since they are properly initialized globals
        instances.vp.branch[v] = False
        instances.vp.loop[v] = False
        instances.vp.recursive[v] = False
        instances.vp.after_scheduler[v] = sched_on
        instances.vp.usually_taken[v] = True
        instances.vp.unique[v] = True
        instances.vp.is_control[v] = isinstance(obj, ControlInstance)

        # There are no sensible defaults for those yet.
        # TODO: Use something other than abb zero for static instances.
        instances.vp.soc[v] = 0
        instances.vp.llvm_soc[v] = 0
        instances.vp.file[v] = ""
        instances.vp.line[v] = 0
        instances.vp.specialization_level[v] = ""
        return v

    def run(self):
        assert self._graph.instances is not None

        # avoid dependency conflicts, therefore import dynamically
        from ara.steps import get_native_component
        ValueAnalyzer = get_native_component("ValueAnalyzer")
        va = ValueAnalyzer(self._graph, current_step.tracer if hasattr(current_step, "tracer") else None)

        Zephyr.config = KConfigFile(self.kconfigfile.get())

        cfg = self._graph.cfg
        callgraph = self._graph.callgraph
        os = self._graph.os

        # Iterate over all statically created instances and convert their dict datatype to the matching datatype.
        # Also fill missing fields in control instances.
        for instance in self._graph.instances.vertices():
            instance_type = locate('ara.os.zephyr.' + self._graph.instances.vp.label[instance])
            inst = instance_type(**self._graph.instances.vp.obj[instance])
            if hasattr(inst, "symbol") and isinstance(inst.symbol, pyllco.Value):
                offset = None
                # Queue handling:
                if isinstance(inst, Queue) and inst.queue_type != QueueType.normal.value:
                    assert isinstance(inst.fake_gep, pyllco.GetElementPtrInst)
                    offset = [inst.fake_gep]
                va.assign_system_object(inst.symbol, inst, offset)
            if issubclass(instance_type, ControlInstance):
                function = cfg.get_function_by_name(inst.entry_name)
                # # try to get the mock thread entry wrapper
                # # z_thread_entry_name = ARA_ENTRY_POINT # Maybe both ARA_ENTRY_POINT and z_thread_entry could be merged in the future
                # z_thread_entry_name = '__ara_mock_z_thread_entry'
                # z_thread_entry = cfg.get_function_by_name(z_thread_entry_name)
                # if z_thread_entry is not None:
                #     function = z_thread_entry
                # else:
                #     logger.warning("%s not found!", z_thread_entry_name)

                inst.cfg = cfg
                inst.function = function
            if issubclass(instance_type, ISR): # user defined ISRs from .intList
                
                func_v = fake_interrupt_function(cfg, callgraph, os, "fake_"+inst.entry_name)
                
                # create the missing IRQ for analysis
                irq = ZephyrIRQ(
                    cpu_id=0, # target CPUID
                    cfg=cfg,
                    artificial=True,
                    function=func_v, #inst.function,
                    id=inst.irq_number,
                    name="IRQCONNECT_"+inst.entry_name,
                    isr_handler=inst,
                    active=True, # the IRQ_CONNECT emits an arch dependent irq registration. irq_enable is then used afterwards
                )

                ZephyrStaticPost.create_static_instance(self._graph.instances, "IRQ", irq, "IRQCONNECT_"+inst.entry_name, False)

            if issubclass(instance_type, Timer):
                inst.cfg = cfg
                expiry_fn_name = inst.expiry_fn
                stop_fn_name = inst.stop_fn

                if expiry_fn_name:
                    expiry_fn = cfg.get_function_by_name(inst.expiry_fn)
                    expiry_instance = ISR(
                        cpu_id=0, # target CPUID
                        cfg=cfg,
                        artificial=False,
                        function=expiry_fn,
                        irq_number=0,
                        priority=0,
                        entry_name=expiry_fn_name,
                        handler_param=None,
                        flags=0,
                    )
                    ZephyrStaticPost.create_static_instance(self._graph.instances, "ISR", expiry_instance, "ISR_" + expiry_fn_name, True)

                if stop_fn_name:
                    stop_fn = cfg.get_function_by_name(inst.stop_fn)
                    stop_instance = ISR(
                        cpu_id=0, # target CPUID
                        cfg=cfg,
                        artificial=False,
                        function=stop_fn,
                        irq_number=0,
                        priority=0,
                        entry_name=stop_fn_name,
                        handler_param=None,
                        flags=0,
                    )
                    ZephyrStaticPost.create_static_instance(self._graph.instances, "ISR", stop_instance, "ISR_" + stop_fn_name, True)


            # Mark the ids of all static instances as used. Since we use symbol names we know
            # them to be unique
            Zephyr.id_count[self._graph.instances.vp.id[instance]] = 1
            self._graph.instances.vp.obj[instance] = inst

        # If there is a main, also add a thread for that.
        # Also, there is no matching abb to give to the vertex
        # NOTE: main() can not be the entry point of a second normal thread because the signature
        # does not match
        main = graph_tool.util.find_vertex(cfg, cfg.vp['name'], 'main')

        if len(main) == 1:
            prio = int(Zephyr.config['CONFIG_MAIN_THREAD_PRIORITY'])
            stack_size = int(Zephyr.config['CONFIG_MAIN_STACK_SIZE'])
            main_thread = Thread(
                cpu_id=-1,
                cfg=cfg,
                artificial=False,
                function=cfg.get_function_by_name(ARA_ENTRY_POINT),
                symbol=None,
                stack=None,
                stack_size=stack_size,
                entry_name="main",
                entry_params=(None, None, None),
                priority=prio,
                options=0,
                delay=0,
                name="main"
            )
            ZephyrStaticPost.create_static_instance(self._graph.instances, "Thread", main_thread, "__main", True)

        # Create a unique node for the Zephyr kernel.
        kernel = ZephyrKernel(heap_size=int(Zephyr.config['CONFIG_HEAP_MEM_POOL_SIZE']), cpu_id=self.cpu_id.get())
        Zephyr.kernel = ZephyrStaticPost.create_static_instance(self._graph.instances, "Zephyr", kernel, "__kernel", False)

        ZephyrOptions.enable_missing_interaction_count = self.enable_missing_interaction_count.get()
        if ZephyrOptions.enable_missing_interaction_count:
            MissingInteractions.activate()


        # create idle threads
        n_cpus = int(Zephyr.config['CONFIG_MP_MAX_NUM_CPUS'])
        for cpu_id in range(n_cpus):
            prio = int(Zephyr.config['CONFIG_NUM_PREEMPT_PRIORITIES'])
            stack_size = int(Zephyr.config['CONFIG_IDLE_STACK_SIZE'])
            idle_thread = Thread(
                cpu_id=cpu_id,
                cfg=cfg,
                artificial=True,
                function=None,
                symbol=None, # f'z_idle_threads[{cpu_id}]',
                stack=None, # f'z_idle_stacks[{cpu_id}]',
                stack_size=stack_size,
                entry_name="idle",
                entry_params=(None, None, None),
                priority=prio,
                options=0,
                delay=0,
                name=f"idle {cpu_id:02d}",
                start_in_init=False
            )
            Zephyr.idle_threads[cpu_id] = ZephyrStaticPost.create_static_instance(self._graph.instances, "Thread", idle_thread, idle_thread.name, True)


        isr_sys_clock_announce = ISR(
            cpu_id=0,
            cfg=cfg,
            artificial=True,
            function=None,
            irq_number=0,
            priority=0,
            entry_name='sys_clock_announce',
            handler_param=None,
            flags=0,
        )

        ZephyrStaticPost.create_static_instance(self._graph.instances, "ISR", isr_sys_clock_announce, "ISR_sys_clock_announce", False)

        irq_sys_clock_announce = ZephyrIRQ(
            cpu_id=0,
            cfg=cfg,
            artificial=True,
            function=None,
            id=0,
            name='sys_clock_announce',
            isr_handler=isr_sys_clock_announce,
            active=False, # TODO: reenable
        )

        ZephyrStaticPost.create_static_instance(self._graph.instances, "IRQ", irq_sys_clock_announce, "IRQ_sys_clock_announce", False)


        if 'CONFIG_TIMESLICING' in Zephyr.config:
            # technically should be handeled by sys_clock_announce
            # but we need to generate a additional state
            # and timeslice does not have advancing time
            irq_z_time_slice = ZephyrIRQ(
                cpu_id=0,
                cfg=cfg,
                artificial=True,
                function=None,
                id=0,
                name='z_time_slice',
                isr_handler=isr_sys_clock_announce,
                active=False,
            )

            ZephyrStaticPost.create_static_instance(self._graph.instances, "IRQ", irq_z_time_slice, "IRQ_z_time_slicing", False)
