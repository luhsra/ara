/**
 ******************** RUN VARIABLES ********************
 */
// current cycle of scheduling
static unsigned cycle = 0;
// the time when a running task is done with its calculations, gets changed when tasks is preempt
static uint32_t calculate_until[TASK_COUNT] = {0};
// keep track what time it was when the task entered its PostTaskHook
static uint32_t time_when_stopped[TASK_COUNT] = {0};

/**
 ******************** DEBUG VARIABLES ********************
 */
#ifdef PRINT_CYCLE_TIMING
	static unsigned int prev = 0;
	static unsigned int cycle_diff[TOTAL_CYLES] = {0};
#endif
#ifdef PRINT_TASK_TIMING
	static unsigned int cycle_count[TASK_COUNT] = {0};
	static unsigned int task_time[TASK_COUNT][CYCLES] = {0};
#endif
#ifdef PRINT_HOOK_STATS
	static unsigned int hookcounter = 0;
	// how many things get tracked in each hook
	static const unsigned int HOOK_VALUES = 5;
	// depening on system load each tasks needs multiple hooks, extend as needed
	static unsigned int hooks[TASK_COUNT*CYCLES*25][HOOK_VALUES] = {0};
	// tracks if any tasks is still running when scheduler starts
	static bool hook_idle = false;
	// used to calculate how long one idle window is
	static uint32_t hook_start_of_idle = 0;
#endif

#ifdef PRINT_RUN_STATS 
	static unsigned start_counter[TASK_COUNT] = {0};
	static unsigned blocked_counter[TASK_COUNT] = {0};
	static unsigned finish_counter[TASK_COUNT] = {0};
#endif
#ifdef PRINT_MEASURED_LOAD
	// tracks if any tasks is still running when scheduler starts
	static bool idle = false;
	// used to calculate how long one idle window is
	static uint32_t start_of_idle = 0;
	static uint32_t idle_total = 0;
#endif


/**
 ******************** ENUMS ********************
 */
// Types of hooks that can are be measured using PRINT_HOOK_STATS
enum hook_type {pre = 1, post = 2, sched = 3};

// Translates from TaskType generated by AUTOSAR to custom enums for tasks in testsuit
task_id translate_task_type(uint32_t task) {
	switch (task){
		case 3:
			return task_id::MS1_id;
		case 4:
			return task_id::MS2_id;
		case 5:
			return task_id::MS5_id;
		case 6:
			return task_id::MS10_id;
		case 7:
			return task_id::MS20_id;
		case 8:
			return task_id::MS50_id;
		case 9:
			return task_id::MS100_id;
		case 10:
			return task_id::MS200_id;
		case 11:
			return task_id::MS1000_id;
		case 12:
			return task_id::MSANGLE_id;
		default:
			return task_id::MS_LAST_id;
	}
}


/**
 ******************** PRINT RESULTS ********************
 */
// Starts cycle_counting in perf and prints name of benchmark
void setup_and_print(const char* name) {

    arch::Perf::start();

    kout << "Run " << name << " testsuit with "<< TASK_COUNT << " Tasks";
	#ifdef ANGLE
		kout << " and Angle-Sync Task";
	#endif
	kout << "." << endl;
	kout << "#CYCLES total/benchmarked: " << TOTAL_CYLES << "/" << CYCLES << endl;
	kout << "#RUNNABLES               : " << NUMBER_OF_RUNABLES << endl;
	#ifdef MEMORY
		kout << "#LABELS (if benchmarked) : " << NUMBER_OF_LABELS << endl;
	#endif
	kout << "*******************\r\n" << endl;

	// to better see results on PI wait at the beginning
	#ifndef QEMU
		micro_sec_wait(2000000);
	#endif

	kout << "\r\n****************\r\nStart" << endl;
}

// After end of run show results, depends on ifdef in parameters.h
void print_results() {

	kout << "End\r\n****************\r\n\n" << endl;
	
	#ifdef PRINT_CYCLE_TIMING
		kout << "*******************\r\nTime between scheduling cycles (expected: " << SCHEDUL_INTERVAL << "us):" << endl;
		for (unsigned i = 0; i < TOTAL_CYLES; i++){
			kout << "Round: " << i << " c: " << cycle_diff[i] / WAIT_FREQUENCE << "us" << endl;
			if (i == FIRST_CYCLE) {
				kout << "Start of run" << endl;
			} else if (i == LAST_CYCLE) {
				kout << "End of run" << endl;
			}
		}
		kout << "*******************\r\n" << endl;
	#endif

	#ifdef PRINT_TASK_TIMING
		kout << "*******************\r\n" << "Time passed between start and completion of a task:" << endl;
		kout << "TASK\t| Iteration\t| TIME_DELTA" << endl;
		kout << "-------------------------------" << endl;
		for (unsigned t = 0; t < TASK_COUNT; t++) {
			for (unsigned i = 0; i < CYCLES; i++) {
				if (task_time[t][i] != 0){
					kout << taskStrings[t] << "\t| " << i << "\t\t| " << task_time[t][i] / WAIT_FREQUENCE << "us" << endl;
				}
			}
		}
		#ifdef ANGLE
			for (unsigned i = 0; i < CYCLES; i++) {
				if (angle_task_time[i] != 0){
					kout << taskStrings[MSANGLE_id] << "\t| " << i << "\t\t| " << angle_task_time[i] / WAIT_FREQUENCE << "us" << endl;
				}
			}
		#endif
		kout << "*******************\r\n" << endl;
	#endif

	#ifdef PRINT_HOOK_STATS
		kout << "*******************\r\n" << "Hook statistics and modified wait_times:" << endl;
		kout << "HOOK_TYPE | TASK | TIME" << endl;
		kout << "-------------------------------" << endl;
		for (unsigned t = 0; t < hookcounter; t++) {
			if (hooks[t][0] == hook_type::post){
				kout << "Post" << "\t  | " << taskStrings[hooks[t][1]] << "  | " << hooks[t][2] / WAIT_FREQUENCE << " us | ";
				
				if (hooks[t][3] != 0){
					kout << "Calculate_until: " << hooks[t][3] / WAIT_FREQUENCE << " us" << "\t| Remaining: ";
					kout << (hooks[t][3] - hooks[t][2] ) / WAIT_FREQUENCE << " us";
				} else {
					kout << "Completed Iteration";
				}
				kout << endl;
				
			} else if (hooks[t][0] == hook_type::pre){
				kout << "Pre " << "\t  | " << taskStrings[hooks[t][1]] << "  | " << hooks[t][2] / WAIT_FREQUENCE << " us | ";
				
				if (hooks[t][3] != 0) {
					kout << "Calculate_until: " << hooks[t][3] / WAIT_FREQUENCE << "us" << "\t| New_End_of_Calculation: ";
					kout << hooks[t][4] / WAIT_FREQUENCE << "us" << " \t| Delta: " << (hooks[t][4] - hooks[t][3]) / WAIT_FREQUENCE << "us";
				} else {
					kout << "Starting new Iteration";
				}
				kout << endl;

			} else if (hooks[t][0] == hook_type::sched) {
				if (FIRST_CYCLE <= hooks[t][1] &&  hooks[t][1] <= LAST_CYCLE){
					kout << "Sched round: " << hooks[t][1] << "  | " << hooks[t][2]/WAIT_FREQUENCE << " us";
					if (hooks[t][3] == true) {
						kout << " Idle for: " << hooks[t][4]/WAIT_FREQUENCE << " us" << endl;
					} else {
						kout << " No Idle" << endl;
					}
				}
			}
		}
		kout << "*******************\r\n" << endl;
	#endif

	#ifdef PRINT_TASK_DATA
		kout << "*******************\r\n" << TASK_COUNT << " different Tasks/Activation Periods (ONLY FOR CALCULATION, NOT MEMORY TIMES):" << endl;
		unsigned exp_runtime = 0;
		unsigned runables = 0;
		unsigned rt_si = 0;
		kout << "TASK     | % of RUNNABLES | #RUNNABLES \t| PERIODE \t| TASK RUNTIME | EXPECTED RUNTIME per SCHEDUL_INTERVAL" << endl;
		kout << "-----------------------------------------------------------------------------------------------" << endl;
		for (unsigned i = 0; i < TASK_COUNT; i++) {
			runables += (NUMBER_OF_RUNABLES / 100) * RUNABLES_SHARE[i];
			exp_runtime = TOTAL_RUNTIME[i];
			rt_si += exp_runtime / RUNABLES_PERIOD[i];
			kout << taskStrings[i] << "\t | " << RUNABLES_SHARE[i] << "\t\t  | " << (NUMBER_OF_RUNABLES / 100) * RUNABLES_SHARE[i] << "\t\t| ";
			kout <<  RUNABLES_PERIOD[i] << "\tus\t | " << exp_runtime << "\tus";
			kout << "\t| " << exp_runtime / RUNABLES_PERIOD[i] << "\tus" << endl;
		}
		#ifdef ANGLE
			runables += (NUMBER_OF_RUNABLES / 100) * RUNABLES_SHARE[MSANGLE_id];
			exp_runtime = TOTAL_RUNTIME[MSANGLE_id];
			kout << taskStrings[MSANGLE_id] << "\t | " << RUNABLES_SHARE[MSANGLE_id] << "\t\t  | " << (NUMBER_OF_RUNABLES / 100) * RUNABLES_SHARE[MSANGLE_id] << "\t\t| ";
			kout <<  SHORTEST_ANGLE_SYNC_PERIOD << "-" << LONGEST_ANGLE_SYNC_PERIOD << " (" << ((SHORTEST_ANGLE_SYNC_PERIOD + LONGEST_ANGLE_SYNC_PERIOD) / 2) << ")";
			kout << " us\t | " << exp_runtime << "\tus";
			kout << "\t| ~" << exp_runtime / ((SHORTEST_ANGLE_SYNC_PERIOD + LONGEST_ANGLE_SYNC_PERIOD) / 2) << "\tus" << endl;
		#endif
		kout << "Active number of runnables=" << runables << " | Needed runtime per interval=" << rt_si;
		// unsigned p = (rt_si * 100) / (SCHEDUL_INTERVAL / 100) / 100;
		kout  << "us (available_interval=" << SCHEDUL_INTERVAL << "us) | Load=" << rt_si / (SCHEDUL_INTERVAL / 100) << "% (Excluding Angle Sync)" << endl;
		kout << "*******************\r\n" << endl;
	#endif


	#if defined(PRINT_MEM_STATS) && defined(MEMORY)
		kout << "*******************\r\nMemory Analysis for up to " << NUMBER_OF_LABELS << " labels with each ";
		kout << AVAERAGE_LABEL_SIZE << " bytes:" << endl;
		kout << "Read-only: " << RO_SHARE << "% | Write-only: - | Intercom: " << RW_SHARE << "%." << endl;
		kout << "TASK\t| RO_SIZE (Bytes) | RO_Offset | INTERCOM_SIZE (Bytes) | INTERCOM_Offset"<< endl;
		kout << "--------------------------------------------------------" << endl;
		unsigned labels = 0;
		for (unsigned i = 0; i < TASK_COUNT; i++) {
			labels += ro_memory_size[i];
			labels += intercom_memory_size[i];
			kout << taskStrings[i] << "\t| " << ro_memory_size[i] << "\t\t| " << ro_memory_offset[i];
			kout << "\t\t| " << intercom_memory_size[i] << "\t\t  | " << intercom_memory_offset[i] << endl;
		}
		#ifdef ANGLE
			kout << taskStrings[MSANGLE_id] << "\t| " << ro_memory_size[MSANGLE_id] << "\t\t  | " << ro_memory_offset[MSANGLE_id];
			kout << "\t| " << intercom_memory_size[MSANGLE_id] << "\t\t| " << intercom_memory_offset[MSANGLE_id] << endl;
		#endif
		kout << "Total used: " << labels << " bytes." << endl;
		kout << "*******************\r\n" << endl;
	#endif

	#ifdef PRINT_RUN_STATS
	kout << "*******************\r\nResults for " << CYCLES << " scheduling cycles:" << endl;
		kout << "TASK\t| #started_runs | #finished_runs | blocked_runs #/%"<< endl;
		kout << "--------------------------------------------------------" << endl;
		for (unsigned i = 0; i < TASK_COUNT; i++) {
			kout << taskStrings[i] << "\t| " << start_counter[i] << "\t\t| " << finish_counter[i] << "\t\t | ";
			kout << blocked_counter[i] << "/" << (100 * blocked_counter[i]) / start_counter[i] << endl;
		}
		#ifdef ANGLE
			kout << "MSANGLE | " << angle_start_counter << "\t\t| " << angle_finish_counter << "\t\t | " << angle_blocked_counter << endl;
		#endif
		kout << "*******************\r\n" << endl;
	#endif

	#ifdef PRINT_MEASURED_LOAD
		kout << "*******************\r\n" << "Idle time:" << endl;
		unsigned long long idle_time = idle_total / WAIT_FREQUENCE;
		unsigned long long runtime = SCHEDUL_INTERVAL * CYCLES;
		kout << "Total Idle Time was: " << (unsigned) idle_time << " us, of a total runtime of: " << (unsigned) runtime << " us." << endl;
		kout << "Idle Cycles were: " << (unsigned) idle_total << " of " << (unsigned) runtime * WAIT_FREQUENCE << endl;
		// care with overflow here
		unsigned long long load = 10000 - (idle_time * 10000 / runtime);
		kout << "Which means load of: " << (unsigned) load / 100 << "." << (unsigned) load % 100 << " %" << endl;
		kout << "*******************\r\n" << endl;
	#endif

	#ifndef QEMU
		// to better see results on PI wait at the end before rebooting
		micro_sec_wait(5000000);
	#endif
}
